export const CATALOG: Record<Locale, Dict> = { en, ro, it };

export function translate(locale: Locale, key: string, vars?: Record<string, string>): string {
  const raw = CATALOG[locale][key] ?? CATALOG[DEFAULT_LOCALE][key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_m, k: string) => vars[k] ?? `{${k}}`);
}
